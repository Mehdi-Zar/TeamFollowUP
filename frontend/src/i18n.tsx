  fr: { admin: "Administrateur", tribe_leader: "Tribe leader", squad_leader: "Squad leader", member: "Membre" },
  en: { admin: "Administrator", tribe_leader: "Tribe leader", squad_leader: "Squad leader", member: "Member" },
