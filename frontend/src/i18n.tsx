interface I18n {
  lang: Lang;
  /** The viewer picking a language. Persisted: it outranks the server default. */
  setLang: (l: Lang) => void;
  /** The instance's configured default, applied only while the viewer has not
   *  picked one. Never persisted, so changing it in Administration reaches
   *  everybody who has not made a choice, not only first-time visitors. */
  applyServerDefault: (l: Lang, force?: boolean) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  rag: (s: Rag) => string;
  roadmap: (s: RoadmapStatus) => string;
  trend: (s: Trend) => string;
  role: (r: string) => string;
  freshness: (f: { age_days: number | null; never_submitted: boolean; is_stale?: boolean }) => string;
  formatDate: (iso?: string | null) => string;
  formatDateTime: (iso?: string | null) => string;
  /** 1 200 000 € in French, €1,200,000 in English: as the exported documents. */
  formatMoney: (n?: number | null) => string;
  /** A number in the app's language (12,5 / 12.5); text passes through. */
  formatNumber: (v?: number | string | null) => string;
}

const I18nContext = createContext<I18n | undefined>(undefined);

/** Where the viewer's explicit language choice lives. */
const LANG_KEY = "trt_lang";

/**
 * The viewer's stored choice, or null when they have not made one.
 *
 * Exported because the distinction between "chosen" and "not chosen yet" is the
 * rule itself, and it must not be re-derived from the raw key by callers.
 */
export function storedLang(): Lang | null {
  const v = localStorage.getItem(LANG_KEY);
  return v === "fr" || v === "en" ? v : null;
}

/**
 * Provides the i18n context. Starts from the viewer's stored choice, mirrors the
 * active language onto `<html lang>`, and builds the translation/formatting
 * functions for consumers.
 *
 * `trt_lang` is written ONLY when the viewer picks a language, and that is the
 * whole point: its presence is what tells `ConfigProvider` that a choice has
 * been made and the instance's `default_lang` must not override it. Writing it
 * from a mount effect, as this used to, stamped "en" into storage before
 * /api/config had even answered, so `default_lang` could never apply and every
 * first-time visitor of a French instance got English.
 */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => storedLang() ?? "en");
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    localStorage.setItem(LANG_KEY, l);
    setLangState(l);
  };
  // `force`: the admin turned the language choice off, so the instance language
  // wins over any stored choice (which is kept, and applies again if it comes back).
  const applyServerDefault = (l: Lang, force = false) => {
    if ((force || !storedLang()) && (l === "fr" || l === "en")) setLangState(l);
  };

  /**
   * Translate `key` for the active language, interpolating any `{name}`
   * placeholders from `vars`. Falls back to the raw key if it's missing, so a
   * missing translation is visible rather than blank.
   */
  const t = (key: string, vars?: Record<string, string | number>) => {
    // Plurals: a "<key>_one" form is used for one (and for zero in French, "0 membre").
    const n = vars && typeof vars.n === "number" ? vars.n : null;
    const one = n !== null && (n === 1 || (lang === "fr" && n === 0)) ? DICT[lang][`${key}_one`] : undefined;
    let s = one ?? DICT[lang][key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, String(vars[k]));
    return s;
  };
  const locale = lang === "fr" ? "fr-FR" : "en-GB";
  const value: I18n = {
    lang,
    setLang,
    applyServerDefault,
    t,
    rag: (s) => RAG[lang][s],
    roadmap: (s) => ROADMAP[lang][s],
    trend: (s) => TREND[lang][s],
    role: (r) => ROLE[lang][r] ?? customRoleLabels[r] ?? r,
    freshness: (f) => {
      if (f.never_submitted || f.age_days === null) return t("fresh.never");
      if (f.age_days === 0) return t("fresh.today");
      if (f.age_days === 1) return t("fresh.one");
      return t("fresh.days", { n: f.age_days });
    },
    formatDate: (iso) => (iso ? new Date(iso).toLocaleDateString(locale, { day: "2-digit", month: "2-digit", year: "numeric" }) : "-"),
    formatDateTime: (iso) =>
      iso ? new Date(iso).toLocaleString(locale, { day: "2-digit", month: "2-digit", year: "numeric", hour: "2-digit", minute: "2-digit" }) : "-",
    formatMoney: (n) => {
      if (n == null) return "-";
      const num = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 }).format(n);
      return lang === "fr" ? `${num}\u00a0€` : `€${num}`;
    },
    formatNumber: (v) => {
      if (v == null || v === "") return "-";
      const n = typeof v === "number" ? v : Number(String(v).replace(",", "."));
      return Number.isFinite(n) ? new Intl.NumberFormat(locale, { maximumFractionDigits: 2 }).format(n) : String(v);
    },
  };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

/**
 * Access the i18n context (`t`, `lang`, `setLang`, and the status/date
 * formatters). Throws if used outside {@link I18nProvider}.
 */
export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
