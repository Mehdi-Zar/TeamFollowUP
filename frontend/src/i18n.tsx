  fr: { admin: "Administrateur", tribe_leader: "Tribe leader", squad_leader: "Squad leader", contributor: "Contributeur", member: "Membre" },
  en: { admin: "Administrator", tribe_leader: "Tribe leader", squad_leader: "Squad leader", contributor: "Contributor", member: "Member" },
